// Pay Index basket versioning — single source of truth for the version
// numbers that gate every basket change.
//
// The basket (job titles + cities in jobs.ts / cities.ts) may ONLY change via
// a bump to BASKET_VERSION accompanied by a dated entry in changelog.ts. This
// is not just a convention: tests/payindex/fingerprint.test.ts recomputes
// BASKET_FINGERPRINT from the live jobs.ts/cities.ts data and fails the suite
// if it no longer matches this checked-in value — so an edit to the basket
// without a version bump breaks the build, not just the docs.
//
// BASKET_FINGERPRINT was generated by
// netlify/functions/_lib/payindex/fingerprint.ts#computeBasketFingerprint
// against the jobs/cities data at BASKET_VERSION 'v1'. Regenerate it with:
//   npx tsx -e "
//     import('./netlify/functions/_lib/payindex/fingerprint.ts').then(async ({ computeBasketFingerprint }) => {
//       const { jobs } = await import('./src/data/payIndex/jobs.ts')
//       const { cities } = await import('./src/data/payIndex/cities.ts')
//       console.log(computeBasketFingerprint(jobs, cities))
//     })
//   "

